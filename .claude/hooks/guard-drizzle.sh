#!/usr/bin/env bash
# PreToolUse guard: nothing writes in drizzle/ except `npm run db:generate`.
# drizzle/ holds the migrations and snapshots drizzle-kit generates from
# src/db/schema.ts. A hand edit, a deleted file or `drizzle-kit drop` puts the
# migrations out of step with the schema and the journal. Exit 2 = block, stderr = reason.
#
# File tools (Write, Edit, MultiEdit, NotebookEdit): blocked when the path is in drizzle/.
# Bash: a statement that touches drizzle/ (names it, or runs after a cd into it) may only
# use read-only commands (ls, cat, grep, git diff, ...); drizzle-kit generate/drop/up are
# blocked everywhere. This is fail-closed pattern matching, not a shell parser: a script
# that writes drizzle/ without naming it on the command line gets through.

FIX="drizzle/ is generated by drizzle-kit and is never edited by hand. Instead: change the schema in src/db/schema.ts, then run \`npm run db:generate\` to generate the migration."
block() { printf 'Blocked by guard-drizzle: %s\n%s\n' "$1" "$FIX" >&2; exit 2; }

command -v jq >/dev/null || block "jq is missing: install it (see the setup guide)"
input=$(cat)
tool=$(jq -r '.tool_name // ""' <<<"$input")
cwd=$(jq -r '.cwd // ""' <<<"$input")
project=${CLAUDE_PROJECT_DIR:-$(cd "$(dirname "$0")/../.." && pwd)}
project=$(realpath -m "$project")
drizzle_dir="$project/drizzle"
[ -n "$cwd" ] || cwd=$project

in_drizzle() { # $1 = absolute, normalized path
  [ "$1" = "$drizzle_dir" ] || [[ "$1" == "$drizzle_dir"/* ]]
}

# ---------- file tools ----------
case "$tool" in
  Write|Edit|MultiEdit|NotebookEdit)
    path=$(jq -r '.tool_input.file_path // .tool_input.notebook_path // ""' <<<"$input")
    [ -n "$path" ] || exit 0
    [[ "$path" == /* ]] || path="$cwd/$path"
    in_drizzle "$(realpath -m "$path")" && block "$tool on $path"
    exit 0 ;;
  Bash) ;;
  *) exit 0 ;;
esac

# ---------- Bash ----------
cmd=$(jq -r '.tool_input.command // ""' <<<"$input")

# "drizzle" as a path component: drizzle, ./drizzle/x, /abs/ticket-bay/drizzle/...
# but not drizzle-kit, drizzle-orm or drizzle.config.ts.
MENTION='(^|[^[:alnum:]_.-])drizzle([/[:space:]"'"'"')*]|$)'
mentions() { grep -Eq "$MENTION" <<<"$1"; }

# Commands that never write files themselves (redirections are checked separately).
READONLY=" cat ls head tail less more grep egrep fgrep rg wc diff cmp stat file du sort uniq cut tr nl comm column jq xxd od md5sum sha1sum sha256sum basename dirname realpath readlink pwd echo printf true test [ cd pushd popd sed find git gh "

first_word() { # skip ( { ! and VAR=value prefixes
  local w
  for w in $1; do
    w=${w#\(}; w=${w#\{}
    [ -z "$w" ] || [ "$w" = "!" ] && continue
    [[ "$w" =~ ^[A-Za-z_][A-Za-z0-9_]*= ]] && continue
    echo "$w"; return
  done
}

stage_readonly() { # $1 = one pipeline stage
  local s=$1 w
  w=$(first_word "$s")
  [ -z "$w" ] && return 0
  [[ "$READONLY" == *" $w "* ]] || return 1
  case "$w" in
    sed)  grep -Eq '(^|[[:space:]])(-[a-zA-Z]*i|--in-place)' <<<"$s" && return 1 ;;
    sort) grep -Eq '(^|[[:space:]])(-[a-zA-Z]*o|--output)' <<<"$s" && return 1 ;;
    find) grep -Eq '(^|[[:space:]])-(delete|exec|execdir|ok|okdir|fprint|fprint0|fprintf|fls)([[:space:]]|$)' <<<"$s" && return 1 ;;
    git)  grep -Eq '^[^[:alnum:]]*git[[:space:]]+(status|diff|log|show|blame|ls-files|grep|add|commit|rev-parse|branch)([[:space:]]|$)' <<<"$s" || return 1 ;;
  esac
  return 0
}

# Output redirections in a statement that touches drizzle/: only to /dev/* or &N,
# or (when not cd'd into drizzle/) to a path that is not in drizzle/.
redirects_ok() { # $1 = statement, $2 = 1 when relative paths resolve inside drizzle/
  local t
  while IFS= read -r t; do
    [ -z "$t" ] && continue
    t=${t#*>}; t=${t#>}; t=${t#|}; t=${t#"${t%%[![:space:]]*}"}
    case "$t" in \&*|/dev/*) continue ;; esac
    mentions "$t" && return 1
    [ "$2" = 1 ] && [[ "$t" != /* ]] && return 1
  done < <(grep -Eo '[0-9&]?>>?\|?[[:space:]]*[^[:space:];&|]+' <<<"$1")
  return 0
}

ctx=0 # 1 once the shell is (or may be) inside drizzle/
in_drizzle "$(realpath -m "$cwd")" && ctx=1

# Split into statements on ; && || & and newlines, then into pipeline stages on |.
statements=$(sed -E 's/(&&|\|\||;)/\n/g; s/([^>&])&([^>&]|$)/\1\n\2/g' <<<"$cmd")
while IFS= read -r st; do
  [ -z "${st//[[:space:]]/}" ] && continue
  IFS='|' read -ra stages <<<"$st"

  for stage in "${stages[@]}"; do
    w=$(first_word "$stage")
    # npm run db:generate is the one way to write drizzle/.
    grep -Eq '^[[:space:]({]*npm[[:space:]]+run(-script)?[[:space:]]+db:generate([[:space:]]|$)' <<<"$stage" && continue
    # drizzle-kit commands that write drizzle/, however they are launched.
    if grep -Eq '(^|[^[:alnum:]_-])drizzle-kit([^[:alnum:]_-]|$)' <<<"$stage" \
       && grep -Eq '(^|[[:space:]])(drop|generate|up)([[:space:]]|$)' <<<"$stage" \
       && ! stage_readonly "$stage"; then
      if grep -Eq '(^|[[:space:]])generate([[:space:]]|$)' <<<"$stage"; then
        block "run drizzle-kit generate through \`npm run db:generate\` (extra flags go after --, e.g. \`npm run db:generate -- --name add_x\`)"
      fi
      block "drizzle-kit drop/up rewrite drizzle/; to undo a migration, revert the change in src/db/schema.ts and run \`npm run db:generate\`"
    fi
    # cd/pushd into drizzle/: later statements run inside it.
    if [ "$w" = cd ] || [ "$w" = pushd ]; then mentions "$stage" && ctx=1; fi
  done

  touches=$ctx
  mentions "$st" && touches=1
  [ "$touches" = 1 ] || continue

  # Command substitution can hide a write behind a read-only first word.
  grep -Eq '\$\(|`|<\(|>\(' <<<"$st" && block "command substitution in a command that touches drizzle/"
  redirects_ok "$st" "$ctx" || block "redirecting output into drizzle/"
  for stage in "${stages[@]}"; do
    grep -Eq '^[[:space:]({]*npm[[:space:]]+run(-script)?[[:space:]]+db:generate([[:space:]]|$)' <<<"$stage" && continue
    stage_readonly "$stage" || block "\`$(first_word "$stage")\` in a command that touches drizzle/ (only read-only commands such as ls, cat, grep and git diff may touch it)"
  done
done <<<"$statements"

exit 0
